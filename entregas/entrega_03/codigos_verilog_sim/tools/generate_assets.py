#!/usr/bin/env python3
from pathlib import Path

OUT = Path("assets")
OUT.mkdir(exist_ok=True)

TRANSPARENT = 0x0843
SPRITE_WORDS = 8192

def rgb565(r, g, b):
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)

def write_hex(path, values, digits=4):
    with open(path, "w", encoding="ascii") as f:
        for value in values:
            f.write(f"{value:0{digits}X}\n")

# ---------------------------------------------------------
# Fondos: 4 imágenes de 64x64.
# ---------------------------------------------------------
backgrounds = []

for bg in range(4):
    for y in range(64):
        for x in range(64):
            if bg == 0:
                c = rgb565(0, 0, 10)
            elif bg == 1:
                c = rgb565(0, 15, 30) if (x // 8) % 2 else rgb565(0, 0, 20)
            elif bg == 2:
                c = rgb565(20, 0, 0) if (y // 8) % 2 else rgb565(0, 0, 0)
            else:
                c = rgb565(x * 4, y * 4, 80)
            backgrounds.append(c)

write_hex(OUT / "backgrounds.hex", backgrounds)

# ---------------------------------------------------------
# Sprites: ID 1 = pala 4x16.
#          ID 2 = pelota / cursor 4x4.
#          ID 3 = damero 4x4 (prueba de transparencia).
# ---------------------------------------------------------
sprites = [TRANSPARENT] * SPRITE_WORDS
metadata = [0] * 256

def add_sprite(sprite_id, width, height, pixels, base):
    assert len(pixels) == width * height
    assert base + len(pixels) <= SPRITE_WORDS
    metadata[sprite_id] = (
        (height << 24) |
        (width << 16) |
        base
    )
    for i, p in enumerate(pixels):
        sprites[base + i] = p

paddle_color = rgb565(255, 255, 255)
ball_color = rgb565(255, 220, 0)

paddle = [paddle_color] * (4 * 16)
ball = [ball_color] * (4 * 4)

T = TRANSPARENT
checker = [ball_color if ((i % 4) + (i // 4)) % 2 == 0 else T for i in range(16)]

add_sprite(1, 4, 16, paddle, 0)
add_sprite(2, 4, 4, ball, 64)
add_sprite(3, 4, 4, checker, 80)

write_hex(OUT / "sprites.hex", sprites)
write_hex(OUT / "sprite_meta.hex", metadata, digits=8)

